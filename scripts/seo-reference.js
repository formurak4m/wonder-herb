/* Derive baseline/seo-reference.json from baseline/head/ — finding 43.
 *
 * WHY THIS FILE EXISTS. `test:seo` asserts part of its contract against the
 * P0-T2 head snapshots. Those snapshots are ~720 KB and could be committed,
 * except that they were captured from live pages carrying finding 26's
 * invented Review / AggregateRating markup. This repository is public and
 * deploys to the client's domain, so they must stay out of it. But a gate
 * whose reference is gitignored cannot run in CI, and P8-T3 put test:seo on
 * the deploy path — so it failed on every run and nothing deployed.
 *
 * This emits ONLY the four things the baseline section of test-seo.js reads:
 * the canonical URL, the JSON-LD @type NAMES, the <title> and the meta
 * description. All four are public marketing markup already in the repository.
 * A @type name is not the fabricated data: no ratingValue, no reviewCount, no
 * patient identity. Review and AggregateRating are dropped here for the same
 * reason test-seo.js dropped them — losing them is the point, not a regression.
 *
 * THE GUARD BELOW IS NOT DECORATION. It refuses to write the file if a rating
 * value, a review count or an author ever reaches it. If this script is one
 * day widened to carry more of the head, that guard is what stops finding 26's
 * material travelling with it. Deleting the guard is the failure mode it
 * exists for; it costs nothing to keep.
 *
 * Regenerated by scripts/baseline.js. Run alone with:  npm run seo:reference
 */
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');

const ROOT = path.join(__dirname, '..');
const HEADS = path.join(ROOT, 'baseline', 'head');
const OUT = path.join(ROOT, 'baseline', 'seo-reference.json');

/* Anything on this list means finding 26's material has reached the file. */
const FORBIDDEN = /ratingValue|reviewCount|bestRating|worstRating|"author"|reviewBody|datePublished/i;

/* EXACTLY the semantics of ldNodes()/typesOf() in scripts/test-seo.js:1176-186 —
   the top level of @graph, or the parsed object itself, and NOT a recursive
   walk. A recursive walk finds nested @types the gate never counted, and the
   comparison would then fail forever on pages whose Product carries a nested
   node. Verified equal across all 18 pages before this file was committed. */
function ldTypes(doc) {
  const out = [];
  doc.querySelectorAll('script[type="application/ld+json"]').forEach(s => {
    let parsed;
    try { parsed = JSON.parse(s.textContent); }
    catch (e) { out.push('BAD_JSON'); return; }
    (parsed['@graph'] || [parsed]).forEach(n => out.push(n && n['@type']));
  });
  return out.sort();
}

const attr = (doc, sel, a) => {
  const el = doc.querySelector(sel);
  return el ? el.getAttribute(a) : null;
};

function build() {
  if (!fs.existsSync(HEADS)) {
    console.error('\nbaseline/head/ is missing — regenerate it with: node scripts/baseline.js\n');
    process.exit(1);
  }
  const pages = {};
  fs.readdirSync(HEADS).filter(f => f.endsWith('.html')).sort().forEach(rel => {
    const doc = new JSDOM(fs.readFileSync(path.join(HEADS, rel), 'utf8')).window.document;
    pages[rel] = {
      canonical: attr(doc, 'link[rel="canonical"]', 'href'),
      /* the same filter test-seo.js applied: these are meant to be lost */
      types: ldTypes(doc).filter(t => t !== 'Review' && t !== 'AggregateRating'),
      title: ((doc.querySelector('title') || {}).textContent || '').trim(),
      description: attr(doc, 'meta[name="description"]', 'content')
    };
  });

  const body = JSON.stringify({
    note: 'Derived from baseline/head/ (P0-T2) by scripts/seo-reference.js. ' +
          'Committed BECAUSE the head snapshots cannot be — see docs/FINDINGS.md finding 43. ' +
          'Regenerate with: npm run seo:reference',
    pages
  }, null, 2) + '\n';

  const hit = body.match(FORBIDDEN);
  if (hit) {
    console.error('\nREFUSED TO WRITE baseline/seo-reference.json: it carries "' + hit[0] +
                  '".\nThat is finding 26 material and this repository is public.\n' +
                  'Fix what this script extracts; do not weaken the guard.\n');
    process.exit(1);
  }

  fs.writeFileSync(OUT, body);
  const n = Object.keys(pages).length;
  console.log('  baseline/seo-reference.json  ' + n + ' page(s), ' +
              (Buffer.byteLength(body) / 1024).toFixed(1) + ' KB, guard clean');
}

if (require.main === module) build();
module.exports = { build, FORBIDDEN };
